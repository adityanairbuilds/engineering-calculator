FLUID_MECHANICS_FORMULAS: list[Formula] = []

FLUID_MECHANICS_FORMULAS.append(
    Formula(
        id="reynolds-number",
        name="Reynolds Number",
        category="Engineering",
        subcategory="Fluid Mechanics",
        equation="Re = ρvD / μ",
        description="Dimensionless number predicting whether fluid flow will be laminar or turbulent.",
        variables=[
            Variable("Re", "Reynolds number", "dimensionless"),
            Variable("rho", "Fluid density", "kg/m³"),
            Variable("v", "Flow velocity", "m/s"),
            Variable("D", "Characteristic diameter", "m"),
            Variable("mu", "Dynamic viscosity", "Pa·s"),
        ],
        keywords=["reynolds number", "laminar flow", "turbulent flow", "fluid mechanics", "viscosity"],
        solve={
            "Re": lambda v: (v["rho"] * v["v"] * v["D"]) / v["mu"],
            "rho": lambda v: (v["Re"] * v["mu"]) / (v["v"] * v["D"]),
            "v": lambda v: (v["Re"] * v["mu"]) / (v["rho"] * v["D"]),
            "D": lambda v: (v["Re"] * v["mu"]) / (v["rho"] * v["v"]),
            "mu": lambda v: (v["rho"] * v["v"] * v["D"]) / v["Re"],
        },
    )
)


def _darcy_weisbach_v(v: dict[str, float]) -> float:
    val = (v["hf"] * v["D"] * 2 * v["g"]) / (v["f"] * v["L"])
    if val < 0:
        raise ValueError("Cannot take the square root of a negative value for these inputs.")
    return math.sqrt(val)


FLUID_MECHANICS_FORMULAS.append(
    Formula(
        id="darcy-weisbach-head-loss",
        name="Darcy-Weisbach Head Loss",
        category="Engineering",
        subcategory="Fluid Mechanics",
        equation="h_f = f(L/D)(v²/2g)",
        description="Calculates the head loss due to friction as fluid flows through a pipe.",
        variables=[
            Variable("hf", "Head loss", "m"),
            Variable("f", "Darcy friction factor", "dimensionless"),
            Variable("L", "Pipe length", "m"),
            Variable("D", "Pipe diameter", "m"),
            Variable("v", "Flow velocity", "m/s"),
            Variable("g", "Gravitational acceleration", "m/s²"),
        ],
        keywords=["darcy-weisbach", "head loss", "pipe friction", "fluid mechanics", "friction factor"],
        solve={
            "hf": lambda v: v["f"] * (v["L"] / v["D"]) * (v["v"] ** 2 / (2 * v["g"])),
            "f": lambda v: (v["hf"] * v["D"] * 2 * v["g"]) / (v["L"] * v["v"] ** 2),
            "L": lambda v: (v["hf"] * v["D"] * 2 * v["g"]) / (v["f"] * v["v"] ** 2),
            "D": lambda v: (v["f"] * v["L"] * v["v"] ** 2) / (v["hf"] * 2 * v["g"]),
            "v": _darcy_weisbach_v,
            "g": lambda v: (v["f"] * v["L"] * v["v"] ** 2) / (v["hf"] * 2 * v["D"]),
        },
    )
)


def _drag_force_v(v: dict[str, float]) -> float:
    val = (2 * v["Fd"]) / (v["rho"] * v["Cd"] * v["A"])
    if val < 0:
        raise ValueError("Cannot take the square root of a negative value for these inputs.")
    return math.sqrt(val)


