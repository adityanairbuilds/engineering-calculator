def _bernoulli_v1(v: dict[str, float]) -> float:
    val = v["v2"] ** 2 + (2 * (v["p2"] - v["p1"])) / v["rho"] + 2 * v["g"] * (v["h2"] - v["h1"])
    if val < 0:
        raise ValueError("Cannot take the square root of a negative value for these inputs.")
    return math.sqrt(val)


def _bernoulli_v2(v: dict[str, float]) -> float:
    val = v["v1"] ** 2 + (2 * (v["p1"] - v["p2"])) / v["rho"] + 2 * v["g"] * (v["h1"] - v["h2"])
    if val < 0:
        raise ValueError("Cannot take the square root of a negative value for these inputs.")
    return math.sqrt(val)


